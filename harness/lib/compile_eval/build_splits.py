"""build_splits.py — Generate the compile-eval split map from real sprint corpus.

Deterministic, artifact-grounded split construction for the Requirement
Compiler eval dataset (N1 dataset layer).  It does NOT fabricate sprint ids:
it reads the real ``*.accepted.md`` corpus (the same regex the loader uses)
and the real sprint artifact directories, then writes:

- ``splits/trainset.txt``
- ``splits/valset.txt``
- ``splits/hard_cases.txt``
- ``splits/hard_cases_categories.json``

Selection is reproducible (sorted by sprint id, fixed slice rule) so reruns
produce identical output.  Hard cases are the artifact-richest sprints, each
assigned to one of the 5 required ``HardCaseCategory`` axes round-robin so all
five axes have minimal coverage.

Run::

    python3 -m lib.compile_eval.build_splits            # default dirs
    python3 lib/compile_eval/build_splits.py --out <dir>
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

try:
    from .dataset import HardCaseCategory
except ImportError:  # Direct script execution documented above.
    from dataset import HardCaseCategory

_ACCEPTED_DIR = Path.home() / "Knowledge" / "_raw" / "solar-harness" / "accepted"
_SPRINTS_DIR = Path.home() / ".solar" / "harness" / "sprints"
_SPLITS_DIR = Path(__file__).resolve().parent / "splits"

_SPRINT_ID_RE = re.compile(r"(sprint-\d{8}-\d{6})\.accepted\.md")

# Artifact name fragments used to rank sprint "richness" for hard-case picks.
_RICHNESS_KEYS = (
    "requirement_ir",
    "requirement-ir",
    "task_graph",
    "closure",
    "acceptance-verdict",
    "coverage-report",
    "handoff",
    "eval",
    "contract",
)

# The 5 required hard-case axes, in a fixed order for round-robin assignment.
_HARD_AXES = [
    HardCaseCategory.MIXED_REQUEST,
    HardCaseCategory.RESEARCH_TO_BUILD,
    HardCaseCategory.APPROVAL_HIGH_RISK,
    HardCaseCategory.EVIDENCE_HEAVY,
    HardCaseCategory.TRACE_COMPLEXITY,
]


def discover_accepted_sprint_ids(accepted_dir: Path) -> list[str]:
    ids: list[str] = []
    if not accepted_dir.exists():
        return ids
    for f in sorted(accepted_dir.glob("*.accepted.md")):
        m = _SPRINT_ID_RE.match(f.name)
        if m:
            ids.append(m.group(1))
    # de-dupe preserving sorted order
    return sorted(dict.fromkeys(ids))


def _sprint_dir_for(sprint_id: str, sprints_dir: Path) -> Path | None:
    if not sprints_dir.exists():
        return None
    for d in sprints_dir.iterdir():
        if d.is_dir() and d.name.startswith(sprint_id):
            return d
    return None


def _richness(sprint_id: str, sprints_dir: Path) -> int:
    d = _sprint_dir_for(sprint_id, sprints_dir)
    if d is None:
        return 0
    try:
        blob = " ".join(p.name for p in d.iterdir())
    except OSError:
        return 0
    return sum(1 for key in _RICHNESS_KEYS if key in blob)


def build_split_assignment(
    *,
    accepted_dir: Path = _ACCEPTED_DIR,
    sprints_dir: Path = _SPRINTS_DIR,
    val_fraction: float = 0.2,
    hard_count: int = 10,
) -> dict[str, object]:
    """Compute (trainset, valset, hard_cases, categories) from real corpus.

    Hard cases: the ``hard_count`` artifact-richest sprints (must have a real
    artifact dir).  Valset: a held-out ``val_fraction`` slice of the remaining
    sprints (deterministic stride).  Trainset: everything else.  Splits are
    mutually exclusive.
    """
    all_ids = discover_accepted_sprint_ids(accepted_dir)
    if not all_ids:
        raise RuntimeError(f"no accepted sprint ids discovered under {accepted_dir}")

    ranked = sorted(
        ((sid, _richness(sid, sprints_dir)) for sid in all_ids),
        key=lambda t: (-t[1], t[0]),
    )
    hard = [sid for sid, score in ranked if score > 0][:hard_count]
    hard_set = set(hard)

    remaining = [sid for sid in all_ids if sid not in hard_set]
    # Deterministic held-out stride for valset.
    stride = max(2, int(round(1.0 / val_fraction))) if val_fraction > 0 else 0
    valset = [sid for i, sid in enumerate(remaining) if stride and i % stride == 0]
    val_set = set(valset)
    trainset = [sid for sid in remaining if sid not in val_set]

    categories: dict[str, list[str]] = {}
    for i, sid in enumerate(hard):
        axis = _HARD_AXES[i % len(_HARD_AXES)]
        categories[sid] = [axis.value]

    return {
        "trainset": trainset,
        "valset": valset,
        "hard_cases": hard,
        "categories": categories,
    }


def write_splits(
    assignment: dict[str, object],
    *,
    out_dir: Path = _SPLITS_DIR,
) -> dict[str, str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: dict[str, str] = {}
    header = "# auto-generated by lib/compile_eval/build_splits.py — do not hand-edit\n"
    for name in ("trainset", "valset", "hard_cases"):
        ids = assignment[name]  # type: ignore[index]
        path = out_dir / f"{name}.txt"
        path.write_text(header + "\n".join(ids) + ("\n" if ids else ""), encoding="utf-8")
        written[name] = str(path)
    cat_path = out_dir / "hard_cases_categories.json"
    cat_path.write_text(
        json.dumps(assignment["categories"], ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    written["hard_cases_categories"] = str(cat_path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="build_splits", description=__doc__)
    parser.add_argument("--accepted-dir", type=Path, default=_ACCEPTED_DIR)
    parser.add_argument("--sprints-dir", type=Path, default=_SPRINTS_DIR)
    parser.add_argument("--out", type=Path, default=_SPLITS_DIR)
    parser.add_argument("--val-fraction", type=float, default=0.2)
    parser.add_argument("--hard-count", type=int, default=10)
    ns = parser.parse_args(argv)

    assignment = build_split_assignment(
        accepted_dir=ns.accepted_dir,
        sprints_dir=ns.sprints_dir,
        val_fraction=ns.val_fraction,
        hard_count=ns.hard_count,
    )
    written = write_splits(assignment, out_dir=ns.out)
    summary = {
        "trainset_count": len(assignment["trainset"]),  # type: ignore[arg-type]
        "valset_count": len(assignment["valset"]),       # type: ignore[arg-type]
        "hard_cases_count": len(assignment["hard_cases"]),  # type: ignore[arg-type]
        "categories_covered": sorted(
            {c for cats in assignment["categories"].values() for c in cats}  # type: ignore[union-attr]
        ),
        "files": written,
    }
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
